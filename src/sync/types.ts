export type Provider = "wix" | "hubspot";

export type SyncDirection =
  | "wix_to_hubspot"
  | "hubspot_to_wix"
  | "bidirectional";

export type FieldTransform = "trim" | "lowercase" | "uppercase" | "none";

export interface NormalizedContact {
  /** Stable contact identifier in the source provider. */
  externalId: string;
  email: string | null;
  firstName: string | null;
  lastName: string | null;
  phone: string | null;
  properties: Record<string, unknown>;
  updatedAt: string | null;
}

export interface FieldMapping {
  wixField: string;
  hubspotProperty: string;
  direction: SyncDirection;
  transform?: FieldTransform;
  enabled: boolean;
}

export interface SyncContext {
  correlationId: string;
  source: Provider;
  receivedAt: string;
  /** Set when the event is known to have been generated by this integration. */
  generatedByIntegration: boolean;
}

export type ConflictDecision =
  | { winner: Provider; reason: "newer_source_timestamp" }
  | { winner: Provider; reason: "only_one_side_changed" }
  | { winner: Provider; reason: "deterministic_tie_break" }
  | { winner: "none"; reason: "no_change" };
